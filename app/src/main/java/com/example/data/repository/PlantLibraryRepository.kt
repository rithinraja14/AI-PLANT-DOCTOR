    fun searchPlants(query: String): List<PlantSpecies> {
        if (query.isBlank()) return plantList
        val lower = query.lowercase().trim()
        return plantList.filter {
            it.name.lowercase().contains(lower) ||
            it.scientificName.lowercase().contains(lower) ||
            it.category.lowercase().contains(lower) ||
            it.commonDiseases.any { d -> d.lowercase().contains(lower) } ||
            it.commonPests.any { p -> p.lowercase().contains(lower) }
        }
    }
